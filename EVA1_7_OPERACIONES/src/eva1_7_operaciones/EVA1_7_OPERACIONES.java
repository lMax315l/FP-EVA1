public class EVA1_7_OPERACIONES {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        //Expresion: Valores, variables, operadores, funciones, que se evaluan para obtener un resultado
        //Aritmetica:
        int suma, val1, val2; //se pueden declarar varuias variables del mismo tipo
        //Asignacion: darle un valor a una variable
        //Operador: simbolo que trabaja sobre identificadores
        //=: asignacion
        //==: comparacion
        val1 = 100; //asignar el 100 en val1
        val2 = 50;
        suma = val1 + val2; //Expresion, asignar la variable suma la operacion entre val1 y val2
        //+: esta entre 2 enteros y se interpreta que se esta sumando
        System.out.print("val1 = ");
        System.out.println(val1);
        System.out.print("val2 = ");
        System.out.println(val2);
        System.out.print("suma = ");
        System.out.println(suma);
        //Operadores
        //* para multiplicar
        
        int multi;
        multi = val1 * val2;
        System.out.print("Multiplicacion = ");
        System.out.println(multi);
        //Division:
        // "/" para dividir
        
        int div;
        div = val1 / val2;
        System.out.print("Division = ");
        System.out.println(div);
        
        val1 = 10;
        val2 = 3;
        div = val1 / val2; 
        System.out.print("val1 = ");
        System.out.println(val1);
        System.out.print("val2 = ");
        System.out.println(val2);
        System.out.print("Division = ");
        System.out.println(div);
        
        double resu;
        resu = val1 / val2;
        System.out.print("Resu = ");
        System.out.println(resu);
        double val2copy;
        val2copy = 3;
        resu = val1 / val2copy;
        System.out.print("Resu = ");
        System.out.println(resu);
        
        
        
       
        
        
        
        
        
        
    }
    
}
